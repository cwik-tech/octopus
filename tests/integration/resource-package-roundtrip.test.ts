test('a skill package preserves complete revision bytes across import restart and export', async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'resource-package-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const repoRoot = path.join(root, 'project');
  await fs.mkdir(path.join(repoRoot, 'agents'), { recursive: true });
  const store = new ResourceLibraryStore({ repoRoot, rootPath: path.join(root, 'library') });
  await store.migrateLegacyResources();
  const service = new ResourcePackageService({ store, repoRoot });
  const archive = await new JSZip()
    .file('portable/SKILL.md', '---\nname: portable\ndescription: Portable instructions. Use when testing packages.\n---\n\n# Portable\n')
    .file('portable/scripts/run.sh', '#!/bin/sh\necho portable\n', { unixPermissions: 0o100755 })
    .generateAsync({ type: 'nodebuffer', platform: 'UNIX' });
  const before = await store.getSnapshot();
  const preview = await service.preview({ bytes: archive, filename: 'portable.zip' });
  assert.equal((await store.getSnapshot()).generation, before.generation);
  assert.equal(preview.skills[0]?.slug, 'portable');
  const receipt = await service.commit({ bytes: archive, filename: 'portable.zip', digest: preview.digest, expectedGeneration: preview.expectedGeneration, resolutions: [] });
  assert.equal(receipt.unchanged, false);
  const restarted = new ResourceLibraryStore({ repoRoot, rootPath: path.join(root, 'library') });
  const snapshot = await restarted.getSnapshot();
  const skill = snapshot.skills.find((item) => item.slug === 'portable');
  assert.ok(skill);
  const files = await restarted.readSkillRevisionSnapshot(skill.id, skill.currentRevisionId);
  assert.equal(files.get('scripts/run.sh')?.contents.toString(), '#!/bin/sh\necho portable\n');
  assert.equal(files.get('scripts/run.sh')?.executable, true);
  assert.equal(snapshot.packages[0]?.origin, 'portable.zip');
  const replay = await service.commit({ bytes: archive, filename: 'portable.zip', digest: preview.digest, expectedGeneration: preview.expectedGeneration, resolutions: [] });
  assert.equal(replay.unchanged, true);
  assert.equal((await store.getSnapshot()).generation, snapshot.generation);
  const exported = await service.export({ kind: 'skill', id: skill.id, format: 'skill', includeHistory: false });
  const secondStore = new ResourceLibraryStore({ repoRoot, rootPath: path.join(root, 'second-library') });
  await secondStore.migrateLegacyResources();
  const second = new ResourcePackageService({ store: secondStore, repoRoot });
  const again = await second.preview({ bytes: exported.bytes, filename: 'again.zip' });
  await second.commit({ bytes: exported.bytes, filename: 'again.zip', digest: again.digest, expectedGeneration: again.expectedGeneration, resolutions: [] });
  const imported = (await secondStore.getSnapshot()).skills[0];
  assert.ok(imported);
  assert.equal((await secondStore.readSkillRevisionSnapshot(imported.id, imported.currentRevisionId)).get('scripts/run.sh')?.contents.toString(), '#!/bin/sh\necho portable\n');
});

test('Agent and Team packages round trip exact dependencies without memory or credentials', async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'resource-team-package-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const repoRoot = path.join(root, 'source');
  await fs.cp(path.resolve('tests/fixtures/team-chat-e2e'), repoRoot, { recursive: true });
  const skillRoot = path.join(repoRoot, 'agents/spec-alpha/skills/planning');
  await fs.mkdir(path.join(skillRoot, 'scripts'), { recursive: true });
  const document = '---\nname: planning\ndescription: Plans exactly. Use when planning.\n---\n\n# Planning\n';
  await fs.writeFile(path.join(skillRoot, 'SKILL.md'), document);
  await fs.writeFile(path.join(skillRoot, 'scripts/helper.sh'), '#!/bin/sh\necho exact\n', { mode: 0o755 });
  await fs.mkdir(path.join(repoRoot, 'agents/spec-alpha/experience'), { recursive: true });
  await fs.writeFile(path.join(repoRoot, 'agents/spec-alpha/experience/private.md'), 'private memory');
  await fs.writeFile(path.join(repoRoot, 'agents/spec-alpha/.env'), 'PRIVATE_TOKEN=never-export');
  const store = new ResourceLibraryStore({ repoRoot, rootPath: path.join(root, 'source-library') });
  await store.migrateLegacyResources();
  const source = new ResourcePackageService({ store, repoRoot });
  const agentExport = await source.export({ kind: 'agent', id: 'spec-alpha', format: 'octopus', includeHistory: false });
  const agentArchive = await JSZip.loadAsync(agentExport.bytes);
  assert.ok(agentArchive.file('agents/spec-alpha/spec-alpha.md'));
  assert.ok(!Object.keys(agentArchive.files).some((name) => /experience|\.env|private\.md/.test(name)));
  const exported = await source.export({ kind: 'team', id: 'board-team', format: 'octopus', includeHistory: false });
  const targetRoot = path.join(root, 'target');
  await fs.mkdir(path.join(targetRoot, 'agents'), { recursive: true });
  await fs.mkdir(path.join(targetRoot, 'teams'), { recursive: true });
  const targetStore = new ResourceLibraryStore({ repoRoot: targetRoot, rootPath: path.join(root, 'target-library') });
  await targetStore.migrateLegacyResources();
  const target = new ResourcePackageService({ store: targetStore, repoRoot: targetRoot });
  const preview = await target.preview({ bytes: exported.bytes, filename: 'board.zip' });
  assert.ok(preview.agents.some((item) => item.id === 'spec-alpha'));
  await target.commit({ bytes: exported.bytes, filename: 'board.zip', digest: preview.digest, expectedGeneration: preview.expectedGeneration, resolutions: [], runtimeTargets: { agents: preview.agents, teams: preview.teams } });
  assert.equal(await fs.readFile(path.join(targetRoot, 'agents/spec-alpha/spec-alpha.md'), 'utf8'), await fs.readFile(path.join(repoRoot, 'agents/spec-alpha/spec-alpha.md'), 'utf8'));
  assert.equal(await fs.readFile(path.join(targetRoot, 'agents/spec-alpha/skills/planning/SKILL.md'), 'utf8'), document);
  assert.equal(await fs.readFile(path.join(targetRoot, 'agents/spec-alpha/skills/planning/scripts/helper.sh'), 'utf8'), '#!/bin/sh\necho exact\n');
  assert.equal((await fs.stat(path.join(targetRoot, 'agents/spec-alpha/skills/planning/scripts/helper.sh'))).mode & 0o111, 0o111);
  assert.equal(await fs.readFile(path.join(targetRoot, 'teams/board-team/team.yaml'), 'utf8'), await fs.readFile(path.join(repoRoot, 'teams/board-team/team.yaml'), 'utf8'));
  const { listAgentTeamOptions } = await import('../../domains/agent-generator/index.js');
  assert.ok(listAgentTeamOptions(targetRoot).some((team) => team.id === 'board-team'), 'Imported Teams must appear in the existing runtime catalog');
  const restarted = new ResourceLibraryStore({ repoRoot: targetRoot, rootPath: path.join(root, 'target-library') });
  assert.ok((await restarted.getSnapshot()).agents.find((item) => item.id === 'spec-alpha')?.attachments.length);
});

test('an imported collection remains exportable after its live Agent is deleted', async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'retained-package-')); t.after(() => fs.rm(root, { recursive: true, force: true }));
  const sourceRoot = path.join(root, 'source'); await fs.mkdir(path.join(sourceRoot, 'agents/alpha'), { recursive: true });
  await fs.writeFile(path.join(sourceRoot, 'agents/alpha/alpha.md'), 'original alpha persona');
  const sourceStore = new ResourceLibraryStore({ repoRoot: sourceRoot, rootPath: path.join(root, 'source-library') }); await sourceStore.migrateLegacyResources();
  const source = new ResourcePackageService({ store: sourceStore, repoRoot: sourceRoot });
  const exported = await source.export({ kind: 'agent', id: 'alpha', format: 'octopus', includeHistory: false });
  const targetRoot = path.join(root, 'target'); await fs.mkdir(path.join(targetRoot, 'agents'), { recursive: true });
  const targetStore = new ResourceLibraryStore({ repoRoot: targetRoot, rootPath: path.join(root, 'target-library') }); await targetStore.migrateLegacyResources();
  const target = new ResourcePackageService({ store: targetStore, repoRoot: targetRoot });
  const preview = await target.preview({ bytes: exported.bytes, filename: 'alpha.zip' });
  const receipt = await target.commit({ bytes: exported.bytes, filename: 'alpha.zip', digest: preview.digest, expectedGeneration: preview.expectedGeneration, resolutions: [], runtimeTargets: { agents: preview.agents, teams: preview.teams } });
  await targetStore.removeAgent('alpha'); await fs.rm(path.join(targetRoot, 'agents/alpha'), { recursive: true });
  const again = await target.export({ kind: 'package', id: receipt.packageId, format: 'octopus', includeHistory: false });
  const archive = await JSZip.loadAsync(again.bytes);
  assert.equal(await archive.file('agents/alpha/alpha.md')?.async('string'), 'original alpha persona');
});

test('retained collection export preserves the local revision selected during import', async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'resolved-package-')); t.after(() => fs.rm(root, { recursive: true, force: true }));
  const sourceRoot = path.join(root, 'source'); const targetRoot = path.join(root, 'target');
  await fs.mkdir(path.join(sourceRoot, 'agents/alpha/skills/planning'), { recursive: true });
  await fs.writeFile(path.join(sourceRoot, 'agents/alpha/alpha.md'), 'alpha persona');
  const document = (body: string) => `---\nname: planning\ndescription: Plans work. Use when planning.\n---\n\n# ${body}\n`;
  await fs.writeFile(path.join(sourceRoot, 'agents/alpha/skills/planning/SKILL.md'), document('upstream'));
  await fs.mkdir(path.join(targetRoot, 'skills/planning'), { recursive: true }); await fs.mkdir(path.join(targetRoot, 'agents'), { recursive: true });
  await fs.writeFile(path.join(targetRoot, 'skills/planning/SKILL.md'), document('local selected revision'));
  const sourceStore = new ResourceLibraryStore({ repoRoot: sourceRoot, rootPath: path.join(root, 'source-library') }); await sourceStore.migrateLegacyResources();
  const source = new ResourcePackageService({ store: sourceStore, repoRoot: sourceRoot });
  const exported = await source.export({ kind: 'agent', id: 'alpha', format: 'octopus', includeHistory: false });
  const targetStore = new ResourceLibraryStore({ repoRoot: targetRoot, rootPath: path.join(root, 'target-library') }); await targetStore.migrateLegacyResources();
  const target = new ResourcePackageService({ store: targetStore, repoRoot: targetRoot });
  const preview = await target.preview({ bytes: exported.bytes, filename: 'alpha.zip' });
  const local = (await targetStore.getSnapshot()).skills[0]; const incoming = preview.skills[0]; assert.ok(local); assert.ok(incoming);
  const receipt = await target.commit({ bytes: exported.bytes, filename: 'alpha.zip', digest: preview.digest, expectedGeneration: preview.expectedGeneration, runtimeTargets: { agents: preview.agents, teams: preview.teams }, resolutions: [{ sourceId: incoming.sourceId, mode: 'reuse', targetSkillId: local.id, revisionId: local.currentRevisionId }] });
  await targetStore.removeAgent('alpha'); await fs.rm(path.join(targetRoot, 'agents/alpha'), { recursive: true });
  const again = await target.export({ kind: 'package', id: receipt.packageId, format: 'octopus', includeHistory: false });
  const archive = await JSZip.loadAsync(again.bytes);
  assert.equal(await archive.file(`skills/${local.id}/${local.currentRevisionId}/SKILL.md`)?.async('string'), document('local selected revision'));
  await assert.rejects(target.export({ kind: 'package', id: receipt.packageId, format: 'skill', includeHistory: false }), /standard|Octopus|format/i);
});
